#!/usr/bin/env python3
"""Import an audio series for the 收听 section (/listen/).

    python3 scripts/listen_import.py <slug> <folder> --title 标题 --author 作者 [--official URL]

Every file in <folder> must start with a three-digit episode number ("004【…】标题.m4a").
Each one is transcoded to 64 kbit/s mono AAC (speech; ~1/3 of a typical download) into
build/listen/<slug>/<NNN>.m4a with clean metadata, and _data/listen/<slug>.yml lists the
episodes with their durations. Audio never enters the repository: upload the output to
the Tencent server, which serves it at /media/listen/<slug>/ (deploy/nginx):

    rsync -rtv build/listen/<slug>/ ubuntu@82.157.7.183:/var/www/media/listen/<slug>/

For a "download all" zip, build it on the server next to the folder (stored, not deflated; entries
named "<NNN><title>.m4a") as /var/www/media/listen/<slug>-<first>-<last>.zip, then add
`archive: "<that name>"` and `archive_mb: <size>` to the yml. Other hand-written fields (cover,
tagline, summary, about) also go above `episodes:`; reruns keep everything there except the
generated slug/title/author/official lines.

Needs ffmpeg/ffprobe. Existing outputs are reused, so rerunning only adds new episodes.
"""

from __future__ import annotations

import argparse
import concurrent.futures
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EPISODE = re.compile(r"^(\d{3})\s*(.+?)\.(?:m4a|mp3|aac|wav|flac|ogg)$", re.IGNORECASE)


def transcode(source: Path, target: Path, title: str, author: str, album: str) -> None:
    if target.exists() and target.stat().st_size > 0:
        return
    tmp = target.with_suffix(".part.m4a")
    subprocess.run(
        ["ffmpeg", "-nostdin", "-y", "-loglevel", "error", "-i", str(source), "-map", "0:a:0",
         "-map_metadata", "-1", "-ac", "1", "-ar", "44100", "-c:a", "aac", "-b:a", "64k",
         "-movflags", "+faststart", "-metadata", f"title={title}", "-metadata", f"artist={author}",
         "-metadata", f"album={album}", str(tmp)],
        check=True,
    )
    tmp.replace(target)


def duration(path: Path) -> int:
    out = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "json", str(path)],
        check=True, capture_output=True, text=True,
    ).stdout
    return round(float(json.loads(out)["format"]["duration"]))


def yaml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("slug", help="lowercase id, e.g. wealth-revolution")
    parser.add_argument("folder", type=Path)
    parser.add_argument("--title", required=True)
    parser.add_argument("--author", required=True)
    parser.add_argument("--official", default="", help="official listening page")
    parser.add_argument("--out", type=Path, help="default: build/listen/<slug>")
    args = parser.parse_args()

    if not re.fullmatch(r"[a-z0-9-]+", args.slug):
        parser.error("slug must contain only lowercase letters, numbers, and hyphens")
    episodes = []
    for path in sorted(args.folder.iterdir()):
        match = EPISODE.match(path.name)
        if match:
            episodes.append((match.group(1), match.group(2).strip(), path))
        elif not path.name.startswith("."):
            print(f"skipped (no three-digit number): {path.name}", file=sys.stderr)
    numbers = [number for number, _, _ in episodes]
    if not episodes or len(set(numbers)) != len(numbers):
        parser.error("need at least one episode and unique episode numbers")

    out = args.out or ROOT / "build" / "listen" / args.slug
    out.mkdir(parents=True, exist_ok=True)
    with concurrent.futures.ThreadPoolExecutor(6) as pool:
        jobs = [pool.submit(transcode, path, out / f"{number}.m4a", path.stem, args.author, args.title)
                for number, _, path in episodes]
        for job in jobs:
            job.result()

    lines = [
        "# Generated by scripts/listen_import.py; audio lives on the Tencent server, not in git.",
        f"slug: {args.slug}",
        f"title: {yaml_string(args.title)}",
        f"author: {yaml_string(args.author)}",
        f"official: {yaml_string(args.official)}",
    ]
    target = ROOT / "_data" / "listen" / f"{args.slug}.yml"
    # Hand-written fields above `episodes:` (archive, cover, summary, about …) survive a rerun;
    # only the comment, slug, title, author and official lines are regenerated.
    if target.exists():
        head = target.read_text(encoding="utf-8").split("\nepisodes:", 1)[0].splitlines()
        lines += [line for line in head
                  if not line.startswith(("# Generated by", "slug:", "title:", "author:", "official:"))]
    lines.append("episodes:")
    for number, title, _ in episodes:
        lines += [f'  - n: "{number}"', f"    title: {yaml_string(title)}",
                  f"    seconds: {duration(out / f'{number}.m4a')}"]
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(episodes)} episodes → {out.relative_to(ROOT) if out.is_relative_to(ROOT) else out} and "
          f"{target.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
